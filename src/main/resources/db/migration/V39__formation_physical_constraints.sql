CREATE TABLE formation_mobility_constraints (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    formation_id BIGINT NOT NULL,
    choir_id BIGINT NOT NULL,
    singer_id BIGINT NOT NULL,
    min_x DECIMAL(10, 3) NOT NULL,
    max_x DECIMAL(10, 3) NOT NULL,
    min_y DECIMAL(10, 3) NOT NULL,
    max_y DECIMAL(10, 3) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_mobility_formation
        FOREIGN KEY (formation_id, choir_id)
        REFERENCES formations (id, choir_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_mobility_singer
        FOREIGN KEY (singer_id, choir_id)
        REFERENCES singers (id, choir_id),

    CONSTRAINT ck_mobility_x_range
        CHECK (min_x < max_x),

    CONSTRAINT ck_mobility_y_range
        CHECK (min_y < max_y)
);

CREATE INDEX idx_formation_mobility_constraints_formation
    ON formation_mobility_constraints (formation_id, choir_id);

CREATE TABLE formation_visibility_constraints (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    formation_id BIGINT NOT NULL,
    choir_id BIGINT NOT NULL,
    protected_singer_id BIGINT NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_visibility_formation
        FOREIGN KEY (formation_id, choir_id)
        REFERENCES formations (id, choir_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_visibility_singer
        FOREIGN KEY (protected_singer_id, choir_id)
        REFERENCES singers (id, choir_id)
);

CREATE INDEX idx_formation_visibility_constraints_formation
    ON formation_visibility_constraints (formation_id, choir_id);
