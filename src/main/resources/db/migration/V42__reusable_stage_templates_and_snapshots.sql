-- CHOIR-157: escenarios físicos reutilizables y snapshots históricos.
-- Unidades: centímetros, DECIMAL(10,3). Aislamiento por coro mediante claves compuestas (id, choir_id).
-- Los detalles se identifican por (padre, seq_no) y se reconstruyen ordenados por seq_no.
-- Elevación: convención de StageElement (CHOIR-155). NOT NULL; > 0 en STEP y PLATFORM; = 0 en el resto.

-- ---------------------------------------------------------------- plantillas

CREATE TABLE stage_templates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    choir_id BIGINT NOT NULL REFERENCES choirs (id),
    name VARCHAR(160) NOT NULL,
    width_cm DECIMAL(10,3) NOT NULL,
    depth_cm DECIMAL(10,3) NOT NULL,
    archived BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT uq_stage_templates_id_choir UNIQUE (id, choir_id),
    CONSTRAINT ck_stage_templates_name CHECK (CHAR_LENGTH(TRIM(name)) > 0),
    CONSTRAINT ck_stage_templates_width CHECK (width_cm > 0),
    CONSTRAINT ck_stage_templates_depth CHECK (depth_cm > 0)
);

CREATE TABLE stage_boundary_points (
    stage_template_id BIGINT NOT NULL,
    choir_id BIGINT NOT NULL,
    seq_no INT NOT NULL,
    x_cm DECIMAL(10,3) NOT NULL,
    y_cm DECIMAL(10,3) NOT NULL,
    CONSTRAINT pk_stage_boundary_points PRIMARY KEY (stage_template_id, seq_no),
    CONSTRAINT fk_stage_boundary_points_template FOREIGN KEY (stage_template_id, choir_id)
        REFERENCES stage_templates (id, choir_id),
    CONSTRAINT ck_stage_boundary_points_seq CHECK (seq_no >= 0),
    CONSTRAINT ck_stage_boundary_points_x CHECK (x_cm >= 0),
    CONSTRAINT ck_stage_boundary_points_y CHECK (y_cm >= 0)
);

CREATE TABLE stage_accesses (
    stage_template_id BIGINT NOT NULL,
    choir_id BIGINT NOT NULL,
    seq_no INT NOT NULL,
    name VARCHAR(160) NOT NULL,
    start_x_cm DECIMAL(10,3) NOT NULL,
    start_y_cm DECIMAL(10,3) NOT NULL,
    end_x_cm DECIMAL(10,3) NOT NULL,
    end_y_cm DECIMAL(10,3) NOT NULL,
    CONSTRAINT pk_stage_accesses PRIMARY KEY (stage_template_id, seq_no),
    CONSTRAINT fk_stage_accesses_template FOREIGN KEY (stage_template_id, choir_id)
        REFERENCES stage_templates (id, choir_id),
    CONSTRAINT ck_stage_accesses_seq CHECK (seq_no >= 0),
    CONSTRAINT ck_stage_accesses_name CHECK (CHAR_LENGTH(TRIM(name)) > 0),
    CONSTRAINT ck_stage_accesses_non_degenerate CHECK (
        start_x_cm <> end_x_cm OR start_y_cm <> end_y_cm),
    CONSTRAINT ck_stage_accesses_coordinates CHECK (
        start_x_cm >= 0 AND start_y_cm >= 0 AND end_x_cm >= 0 AND end_y_cm >= 0)
);

CREATE TABLE stage_elements (
    stage_template_id BIGINT NOT NULL,
    choir_id BIGINT NOT NULL,
    seq_no INT NOT NULL,
    name VARCHAR(160) NOT NULL,
    element_type VARCHAR(20) NOT NULL,
    x_cm DECIMAL(10,3) NOT NULL,
    y_cm DECIMAL(10,3) NOT NULL,
    width_cm DECIMAL(10,3) NOT NULL,
    depth_cm DECIMAL(10,3) NOT NULL,
    elevation_cm DECIMAL(10,3) NOT NULL,
    CONSTRAINT pk_stage_elements PRIMARY KEY (stage_template_id, seq_no),
    CONSTRAINT fk_stage_elements_template FOREIGN KEY (stage_template_id, choir_id)
        REFERENCES stage_templates (id, choir_id),
    CONSTRAINT ck_stage_elements_seq CHECK (seq_no >= 0),
    CONSTRAINT ck_stage_elements_name CHECK (CHAR_LENGTH(TRIM(name)) > 0),
    CONSTRAINT ck_stage_elements_type CHECK (element_type IN
        ('BENCH', 'PIANO', 'FURNITURE', 'OBSTACLE', 'STEP', 'PLATFORM')),
    CONSTRAINT ck_stage_elements_x CHECK (x_cm >= 0),
    CONSTRAINT ck_stage_elements_y CHECK (y_cm >= 0),
    CONSTRAINT ck_stage_elements_width CHECK (width_cm > 0),
    CONSTRAINT ck_stage_elements_depth CHECK (depth_cm > 0),
    CONSTRAINT ck_stage_elements_elevation CHECK (
        (element_type IN ('STEP', 'PLATFORM') AND elevation_cm > 0)
        OR (element_type IN ('BENCH', 'PIANO', 'FURNITURE', 'OBSTACLE') AND elevation_cm = 0))
);

-- ---------------------------------------------------------------- snapshots

CREATE TABLE concert_stage_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    choir_id BIGINT NOT NULL,
    concert_id BIGINT NOT NULL,
    repertoire_item_id BIGINT NOT NULL,
    source_template_id BIGINT NOT NULL,
    name VARCHAR(160) NOT NULL,
    width_cm DECIMAL(10,3) NOT NULL,
    depth_cm DECIMAL(10,3) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uq_concert_stage_snapshots_id_choir UNIQUE (id, choir_id),
    CONSTRAINT uq_concert_stage_snapshots_inclusion UNIQUE (concert_id, repertoire_item_id),
    CONSTRAINT fk_concert_stage_snapshots_concert FOREIGN KEY (concert_id, choir_id)
        REFERENCES concerts (id, choir_id),
    CONSTRAINT fk_concert_stage_snapshots_repertoire FOREIGN KEY (repertoire_item_id, choir_id)
        REFERENCES repertoire_items (id, choir_id),
    CONSTRAINT fk_concert_stage_snapshots_inclusion FOREIGN KEY (concert_id, repertoire_item_id)
        REFERENCES concert_repertoire (concert_id, repertoire_item_id),
    CONSTRAINT fk_concert_stage_snapshots_source FOREIGN KEY (source_template_id, choir_id)
        REFERENCES stage_templates (id, choir_id) ON DELETE RESTRICT,
    CONSTRAINT ck_concert_stage_snapshots_name CHECK (CHAR_LENGTH(TRIM(name)) > 0),
    CONSTRAINT ck_concert_stage_snapshots_width CHECK (width_cm > 0),
    CONSTRAINT ck_concert_stage_snapshots_depth CHECK (depth_cm > 0)
);

CREATE TABLE concert_stage_snapshot_boundary_points (
    snapshot_id BIGINT NOT NULL,
    choir_id BIGINT NOT NULL,
    seq_no INT NOT NULL,
    x_cm DECIMAL(10,3) NOT NULL,
    y_cm DECIMAL(10,3) NOT NULL,
    CONSTRAINT pk_concert_stage_snapshot_boundary_points PRIMARY KEY (snapshot_id, seq_no),
    CONSTRAINT fk_snapshot_boundary_points_snapshot FOREIGN KEY (snapshot_id, choir_id)
        REFERENCES concert_stage_snapshots (id, choir_id),
    CONSTRAINT ck_snapshot_boundary_points_seq CHECK (seq_no >= 0),
    CONSTRAINT ck_snapshot_boundary_points_x CHECK (x_cm >= 0),
    CONSTRAINT ck_snapshot_boundary_points_y CHECK (y_cm >= 0)
);

CREATE TABLE concert_stage_snapshot_accesses (
    snapshot_id BIGINT NOT NULL,
    choir_id BIGINT NOT NULL,
    seq_no INT NOT NULL,
    name VARCHAR(160) NOT NULL,
    start_x_cm DECIMAL(10,3) NOT NULL,
    start_y_cm DECIMAL(10,3) NOT NULL,
    end_x_cm DECIMAL(10,3) NOT NULL,
    end_y_cm DECIMAL(10,3) NOT NULL,
    CONSTRAINT pk_concert_stage_snapshot_accesses PRIMARY KEY (snapshot_id, seq_no),
    CONSTRAINT fk_snapshot_accesses_snapshot FOREIGN KEY (snapshot_id, choir_id)
        REFERENCES concert_stage_snapshots (id, choir_id),
    CONSTRAINT ck_snapshot_accesses_seq CHECK (seq_no >= 0),
    CONSTRAINT ck_snapshot_accesses_name CHECK (CHAR_LENGTH(TRIM(name)) > 0),
    CONSTRAINT ck_snapshot_accesses_non_degenerate CHECK (
        start_x_cm <> end_x_cm OR start_y_cm <> end_y_cm),
    CONSTRAINT ck_snapshot_accesses_coordinates CHECK (
        start_x_cm >= 0 AND start_y_cm >= 0 AND end_x_cm >= 0 AND end_y_cm >= 0)
);

CREATE TABLE concert_stage_snapshot_elements (
    snapshot_id BIGINT NOT NULL,
    choir_id BIGINT NOT NULL,
    seq_no INT NOT NULL,
    name VARCHAR(160) NOT NULL,
    element_type VARCHAR(20) NOT NULL,
    x_cm DECIMAL(10,3) NOT NULL,
    y_cm DECIMAL(10,3) NOT NULL,
    width_cm DECIMAL(10,3) NOT NULL,
    depth_cm DECIMAL(10,3) NOT NULL,
    elevation_cm DECIMAL(10,3) NOT NULL,
    CONSTRAINT pk_concert_stage_snapshot_elements PRIMARY KEY (snapshot_id, seq_no),
    CONSTRAINT fk_snapshot_elements_snapshot FOREIGN KEY (snapshot_id, choir_id)
        REFERENCES concert_stage_snapshots (id, choir_id),
    CONSTRAINT ck_snapshot_elements_seq CHECK (seq_no >= 0),
    CONSTRAINT ck_snapshot_elements_name CHECK (CHAR_LENGTH(TRIM(name)) > 0),
    CONSTRAINT ck_snapshot_elements_type CHECK (element_type IN
        ('BENCH', 'PIANO', 'FURNITURE', 'OBSTACLE', 'STEP', 'PLATFORM')),
    CONSTRAINT ck_snapshot_elements_x CHECK (x_cm >= 0),
    CONSTRAINT ck_snapshot_elements_y CHECK (y_cm >= 0),
    CONSTRAINT ck_snapshot_elements_width CHECK (width_cm > 0),
    CONSTRAINT ck_snapshot_elements_depth CHECK (depth_cm > 0),
    CONSTRAINT ck_snapshot_elements_elevation CHECK (
        (element_type IN ('STEP', 'PLATFORM') AND elevation_cm > 0)
        OR (element_type IN ('BENCH', 'PIANO', 'FURNITURE', 'OBSTACLE') AND elevation_cm = 0))
);

-- ---------------------------------------------------------------- índices

CREATE INDEX idx_stage_templates_choir_archived ON stage_templates (choir_id, archived);
CREATE INDEX idx_concert_stage_snapshots_source ON concert_stage_snapshots (choir_id, source_template_id);
