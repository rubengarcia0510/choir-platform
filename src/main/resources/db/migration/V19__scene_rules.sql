CREATE TABLE scene_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repertoire_item_id BIGINT NOT NULL
        REFERENCES repertoire_items(id) ON DELETE CASCADE,
    rule_order INTEGER NOT NULL,
    rule_type VARCHAR(30) NOT NULL,
    description VARCHAR(1000) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_scene_rule_order
        CHECK (rule_order >= 0),
    CONSTRAINT ck_scene_rule_type
        CHECK (rule_type IN ('MOVEMENT', 'EXIT', 'CAST_DIVISION')),
    CONSTRAINT uq_scene_rule_order
        UNIQUE (repertoire_item_id, rule_order)
);

CREATE INDEX idx_scene_rules_repertoire_active
    ON scene_rules (repertoire_item_id, active, rule_order);

CREATE TABLE scene_rule_groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scene_rule_id BIGINT NOT NULL
        REFERENCES scene_rules(id) ON DELETE CASCADE,
    group_order INTEGER NOT NULL,
    group_label VARCHAR(100) NOT NULL,
    member_count INTEGER NOT NULL,

    CONSTRAINT ck_scene_rule_group_order
        CHECK (group_order >= 0),
    CONSTRAINT ck_scene_rule_member_count
        CHECK (member_count > 0),
    CONSTRAINT uq_scene_rule_group_order
        UNIQUE (scene_rule_id, group_order)
);

CREATE INDEX idx_scene_rule_groups_rule
    ON scene_rule_groups (scene_rule_id, group_order);
