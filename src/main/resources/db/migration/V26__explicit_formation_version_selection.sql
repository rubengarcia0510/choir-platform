    ADD CONSTRAINT uq_formation_id_occurrence
    UNIQUE (id, concert_id, repertoire_item_id);

ALTER TABLE formation_versions
    ADD CONSTRAINT uq_formation_version_id_formation
    UNIQUE (id, formation_id);

ALTER TABLE concert_repertoire
    ADD COLUMN selected_formation_id BIGINT;

ALTER TABLE concert_repertoire
    ADD COLUMN selected_formation_version_id BIGINT;

ALTER TABLE concert_repertoire
    ADD CONSTRAINT ck_concert_repertoire_selection_complete
    CHECK (
        (
            selected_formation_id IS NULL
            AND selected_formation_version_id IS NULL
        )
        OR
        (
            selected_formation_id IS NOT NULL
            AND selected_formation_version_id IS NOT NULL
        )
    );

ALTER TABLE concert_repertoire
    ADD CONSTRAINT fk_concert_repertoire_selected_formation
    FOREIGN KEY (
        selected_formation_id,
        concert_id,
        repertoire_item_id
    )
    REFERENCES formations (
        id,
        concert_id,
        repertoire_item_id
    );

ALTER TABLE concert_repertoire
    ADD CONSTRAINT fk_concert_repertoire_selected_version
    FOREIGN KEY (
        selected_formation_version_id,
        selected_formation_id
    )
    REFERENCES formation_versions (id, formation_id);

CREATE TABLE formation_version_selection_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    concert_id BIGINT NOT NULL,
    repertoire_item_id BIGINT NOT NULL,
    previous_formation_id BIGINT,
    previous_formation_version_id BIGINT,
    selected_formation_id BIGINT NOT NULL,
    selected_formation_version_id BIGINT NOT NULL,
    actor_email VARCHAR(254) NOT NULL,
    selected_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_formation_selection_history_occurrence
        FOREIGN KEY (concert_id, repertoire_item_id)
        REFERENCES concert_repertoire (concert_id, repertoire_item_id),

    CONSTRAINT fk_formation_selection_history_previous_formation
        FOREIGN KEY (
            previous_formation_id,
            concert_id,
            repertoire_item_id
        )
        REFERENCES formations (
            id,
            concert_id,
            repertoire_item_id
        ),

    CONSTRAINT fk_formation_selection_history_previous_version
        FOREIGN KEY (
            previous_formation_version_id,
            previous_formation_id
        )
        REFERENCES formation_versions (id, formation_id),

    CONSTRAINT fk_formation_selection_history_selected_formation
        FOREIGN KEY (
            selected_formation_id,
            concert_id,
            repertoire_item_id
        )
        REFERENCES formations (
            id,
            concert_id,
            repertoire_item_id
        ),

    CONSTRAINT fk_formation_selection_history_selected_version
        FOREIGN KEY (
            selected_formation_version_id,
            selected_formation_id
        )
        REFERENCES formation_versions (id, formation_id),

    CONSTRAINT ck_formation_selection_history_previous_complete
        CHECK (
            (
                previous_formation_id IS NULL
                AND previous_formation_version_id IS NULL
            )
            OR
            (
                previous_formation_id IS NOT NULL
                AND previous_formation_version_id IS NOT NULL
            )
        )
);

CREATE INDEX idx_formation_selection_history_occurrence
    ON formation_version_selection_history (
        concert_id,
        repertoire_item_id,
        selected_at,
        id
    );
