CREATE TABLE transition_publication_evidence (
    transition_version_id BIGINT PRIMARY KEY
        REFERENCES transition_versions(id),
    evaluation_id BIGINT NOT NULL UNIQUE
        REFERENCES transition_rule_evaluations(id),
    transition_id BIGINT NOT NULL REFERENCES transitions(id),
    from_formation_version_id BIGINT NOT NULL
        REFERENCES formation_versions(id),
    to_formation_version_id BIGINT NOT NULL
        REFERENCES formation_versions(id),
    separation_settings_revision BIGINT NOT NULL
        REFERENCES scene_rule_separation_setting_revisions(revision),
    global_separation_threshold DECIMAL(10, 7) NOT NULL,
    published_by_email VARCHAR(254) NOT NULL,
    published_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_transition_publication_evidence_threshold
        CHECK (
            global_separation_threshold > 0
            AND global_separation_threshold * global_separation_threshold <= 2
        ),
    CONSTRAINT ck_transition_publication_evidence_formations
        CHECK (from_formation_version_id <> to_formation_version_id)
);

CREATE TABLE transition_publication_decisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluation_id BIGINT NOT NULL
        REFERENCES transition_rule_evaluations(id),
    transition_version_id BIGINT NOT NULL
        REFERENCES transition_versions(id),
    result_order INTEGER NOT NULL DEFAULT -1,
    warning_order INTEGER NOT NULL,
    warning_code VARCHAR(100) NOT NULL,
    warning_explanation VARCHAR(1000) NOT NULL,
    decision VARCHAR(20) NOT NULL,
    director_email VARCHAR(254) NOT NULL,
    reason VARCHAR(1000) NOT NULL,
    decided_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_transition_publication_decision
        CHECK (decision = 'ACCEPTED'),
    CONSTRAINT ck_transition_publication_decision_warning_order
        CHECK (warning_order >= 0),
    CONSTRAINT ck_transition_publication_decision_result_order
        CHECK (result_order >= -1),
    CONSTRAINT uq_transition_publication_decision_warning
        UNIQUE (evaluation_id, result_order, warning_order)
);

CREATE INDEX idx_transition_publication_decisions_version
    ON transition_publication_decisions (transition_version_id, evaluation_id);
