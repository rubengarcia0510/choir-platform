ALTER TABLE concerts
    ADD COLUMN cast_configured BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE concert_cast_selections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    concert_id BIGINT NOT NULL,
    choir_id BIGINT NOT NULL,
    singer_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_cast_selection_concert
        FOREIGN KEY (concert_id, choir_id)
        REFERENCES concerts (id, choir_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_cast_selection_singer
        FOREIGN KEY (singer_id, choir_id)
        REFERENCES singers (id, choir_id),

    CONSTRAINT uq_cast_selection
        UNIQUE (concert_id, singer_id)
);

CREATE INDEX idx_cast_selection_concert
    ON concert_cast_selections (concert_id);
