CREATE TABLE vocal_sections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    choir_id BIGINT NOT NULL REFERENCES choirs(id),
    name VARCHAR(80) NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_vocal_section_name_per_choir
        UNIQUE (choir_id, name),
    CONSTRAINT uq_vocal_section_id_choir
        UNIQUE (id, choir_id),
    CONSTRAINT ck_vocal_section_sort_order
        CHECK (sort_order >= 0)
);

ALTER TABLE singers
    ADD COLUMN voice_section_id BIGINT;

ALTER TABLE singers
    ADD CONSTRAINT fk_singer_vocal_section_same_choir
    FOREIGN KEY (voice_section_id, choir_id)
    REFERENCES vocal_sections (id, choir_id);

CREATE INDEX idx_vocal_sections_choir
    ON vocal_sections (choir_id);
