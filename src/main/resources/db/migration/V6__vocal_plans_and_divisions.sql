CREATE TABLE vocal_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repertoire_item_id BIGINT NOT NULL,
    choir_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_vocal_plan_per_work UNIQUE (repertoire_item_id),
    CONSTRAINT uq_vocal_plan_id_choir UNIQUE (id, choir_id),
    CONSTRAINT fk_vocal_plan_work_same_choir
        FOREIGN KEY (repertoire_item_id, choir_id)
        REFERENCES repertoire_items (id, choir_id)
);

CREATE TABLE vocal_plan_divisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vocal_plan_id BIGINT NOT NULL,
    choir_id BIGINT NOT NULL,
    vocal_section_id BIGINT NOT NULL,
    division_number INTEGER NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_vocal_division_number CHECK (division_number > 0),
    CONSTRAINT uq_vocal_division_plan_section_number
        UNIQUE (vocal_plan_id, vocal_section_id, division_number),
    CONSTRAINT uq_vocal_division_id_plan
        UNIQUE (id, vocal_plan_id),
    CONSTRAINT fk_vocal_division_plan_same_choir
        FOREIGN KEY (vocal_plan_id, choir_id)
        REFERENCES vocal_plans (id, choir_id),
    CONSTRAINT fk_vocal_division_section_same_choir
        FOREIGN KEY (vocal_section_id, choir_id)
        REFERENCES vocal_sections (id, choir_id)
);

CREATE INDEX idx_vocal_plan_divisions_plan
    ON vocal_plan_divisions (vocal_plan_id);

CREATE INDEX idx_vocal_plan_divisions_section
    ON vocal_plan_divisions (vocal_section_id);
