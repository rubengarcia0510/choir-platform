-- CHOIR-61: historial de asignaciones vocales por obra.
-- La división corresponde a una asignación concreta, no al elenco global.
-- Los datos descriptivos se conservan aunque cambien las entidades actuales.

CREATE TABLE concert_vocal_assignment_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    concert_id BIGINT NOT NULL,
    repertoire_item_id BIGINT NOT NULL,
    source_singer_id BIGINT,
    singer_name_snapshot VARCHAR(160) NOT NULL,
    voice_part_snapshot VARCHAR(40),
    voice_section_id_snapshot BIGINT,
    voice_section_name_snapshot VARCHAR(80),
    division_number_snapshot INTEGER NOT NULL,
    captured_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_vocal_assignment_snapshot_occurrence
        FOREIGN KEY (concert_id, repertoire_item_id)
        REFERENCES concert_repertoire (concert_id, repertoire_item_id),

    CONSTRAINT fk_vocal_assignment_snapshot_singer
        FOREIGN KEY (source_singer_id)
        REFERENCES singers(id) ON DELETE SET NULL,

    CONSTRAINT ck_vocal_assignment_snapshot_division
        CHECK (division_number_snapshot > 0),

    CONSTRAINT uq_vocal_assignment_snapshot
        UNIQUE (concert_id, repertoire_item_id, source_singer_id)
);

CREATE INDEX idx_vocal_assignment_snapshot_occurrence
    ON concert_vocal_assignment_snapshots (concert_id, repertoire_item_id);

CREATE INDEX idx_vocal_assignment_snapshot_singer
    ON concert_vocal_assignment_snapshots (source_singer_id);
