CREATE TABLE scene_rule_revisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scene_rule_id BIGINT NOT NULL,
    revision_number INTEGER NOT NULL,
    repertoire_item_id BIGINT NOT NULL,
    rule_order INTEGER NOT NULL,
    rule_type VARCHAR(30) NOT NULL,
    description VARCHAR(1000) NOT NULL,
    active BOOLEAN NOT NULL,
    revision_kind VARCHAR(20) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_scene_rule_revision
        UNIQUE (scene_rule_id, revision_number),
    CONSTRAINT ck_scene_rule_revision_number
        CHECK (revision_number > 0),
    CONSTRAINT ck_scene_rule_revision_order
        CHECK (rule_order >= 0),
    CONSTRAINT ck_scene_rule_revision_type
        CHECK (rule_type IN ('MOVEMENT', 'EXIT', 'CAST_DIVISION')),
    CONSTRAINT ck_scene_rule_revision_kind
        CHECK (revision_kind IN (
            'BASELINE', 'CREATE', 'UPDATE', 'REORDER', 'DEACTIVATE'
        ))
);

CREATE INDEX idx_scene_rule_revisions_rule
    ON scene_rule_revisions (scene_rule_id, revision_number);

CREATE TABLE scene_rule_revision_groups (
    revision_id BIGINT NOT NULL
        REFERENCES scene_rule_revisions(id),
    group_order INTEGER NOT NULL,
    group_label VARCHAR(100) NOT NULL,
    member_count INTEGER NOT NULL,

    CONSTRAINT pk_scene_rule_revision_groups
        PRIMARY KEY (revision_id, group_order),
    CONSTRAINT ck_scene_rule_revision_group_order
        CHECK (group_order >= 0),
    CONSTRAINT ck_scene_rule_revision_member_count
        CHECK (member_count > 0)
);

INSERT INTO scene_rule_revisions (
    scene_rule_id,
    revision_number,
    repertoire_item_id,
    rule_order,
    rule_type,
    description,
    active,
    revision_kind,
    created_at
)
SELECT
    id,
    1,
    repertoire_item_id,
    rule_order,
    rule_type,
    description,
    active,
    'BASELINE',
    CURRENT_TIMESTAMP
FROM scene_rules;

INSERT INTO scene_rule_revision_groups (
    revision_id,
    group_order,
    group_label,
    member_count
)
SELECT
    revision.id,
    current_group.group_order,
    current_group.group_label,
    current_group.member_count
FROM scene_rule_groups current_group
JOIN scene_rule_revisions revision
    ON revision.scene_rule_id = current_group.scene_rule_id
   AND revision.revision_number = 1;
