ALTER TABLE concerts
    ADD CONSTRAINT uq_concert_id_choir UNIQUE (id, choir_id);

ALTER TABLE vocal_plan_divisions
    ADD CONSTRAINT uq_vocal_division_id_choir UNIQUE (id, choir_id);

CREATE TABLE concert_vocal_adjustments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    concert_id BIGINT NOT NULL,
    repertoire_item_id BIGINT NOT NULL,
    choir_id BIGINT NOT NULL,
    notes VARCHAR(2000),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_concert_vocal_adjustment
        UNIQUE (concert_id, repertoire_item_id),

    CONSTRAINT fk_adjustment_occurrence
        FOREIGN KEY (concert_id, repertoire_item_id)
        REFERENCES concert_repertoire (concert_id, repertoire_item_id),

    CONSTRAINT fk_adjustment_concert_choir
        FOREIGN KEY (concert_id, choir_id)
        REFERENCES concerts (id, choir_id),

    CONSTRAINT fk_adjustment_work_choir
        FOREIGN KEY (repertoire_item_id, choir_id)
        REFERENCES repertoire_items (id, choir_id)
);

CREATE TABLE concert_vocal_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    concert_id BIGINT NOT NULL,
    repertoire_item_id BIGINT NOT NULL,
    singer_id BIGINT NOT NULL,
    vocal_plan_division_id BIGINT NOT NULL,
    choir_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_concert_vocal_assignment
        UNIQUE (concert_id, repertoire_item_id, singer_id),

    CONSTRAINT fk_assignment_occurrence
        FOREIGN KEY (concert_id, repertoire_item_id)
        REFERENCES concert_repertoire (concert_id, repertoire_item_id),

    CONSTRAINT fk_assignment_concert_choir
        FOREIGN KEY (concert_id, choir_id)
        REFERENCES concerts (id, choir_id),

    CONSTRAINT fk_assignment_work_choir
        FOREIGN KEY (repertoire_item_id, choir_id)
        REFERENCES repertoire_items (id, choir_id),

    CONSTRAINT fk_assignment_singer_choir
        FOREIGN KEY (singer_id, choir_id)
        REFERENCES singers (id, choir_id),

    CONSTRAINT fk_assignment_division_choir
        FOREIGN KEY (vocal_plan_division_id, choir_id)
        REFERENCES vocal_plan_divisions (id, choir_id)
);

CREATE INDEX idx_concert_vocal_adjustments_occurrence
    ON concert_vocal_adjustments (concert_id, repertoire_item_id);

CREATE INDEX idx_concert_vocal_assignments_occurrence
    ON concert_vocal_assignments (concert_id, repertoire_item_id);

CREATE INDEX idx_concert_vocal_assignments_division
    ON concert_vocal_assignments (vocal_plan_division_id);
