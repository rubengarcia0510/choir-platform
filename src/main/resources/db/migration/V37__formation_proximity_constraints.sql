CREATE TABLE formation_proximity_constraints (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    formation_id BIGINT NOT NULL,
    choir_id BIGINT NOT NULL,
    singer_one_id BIGINT NOT NULL,
    singer_two_id BIGINT NOT NULL,
    max_distance DECIMAL(10, 3) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_proximity_formation
        FOREIGN KEY (formation_id, choir_id)
        REFERENCES formations (id, choir_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_proximity_singer_one
        FOREIGN KEY (singer_one_id, choir_id)
        REFERENCES singers (id, choir_id),

    CONSTRAINT fk_proximity_singer_two
        FOREIGN KEY (singer_two_id, choir_id)
        REFERENCES singers (id, choir_id),

    CONSTRAINT ck_proximity_distinct_singers
        CHECK (singer_one_id < singer_two_id),

    CONSTRAINT ck_proximity_max_distance
        CHECK (max_distance > 0),

    CONSTRAINT uq_formation_proximity_pair
        UNIQUE (formation_id, singer_one_id, singer_two_id)
);

CREATE INDEX idx_formation_proximity_active
    ON formation_proximity_constraints (formation_id, active);
