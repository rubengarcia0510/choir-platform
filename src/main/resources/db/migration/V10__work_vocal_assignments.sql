-- CHOIR-62: asignaciones vocales independientes por obra.
-- Las claves compuestas impiden cruzar obras, coros, planes y divisiones.

ALTER TABLE vocal_plans
    ADD CONSTRAINT uq_vocal_plan_id_work_choir
    UNIQUE (id, repertoire_item_id, choir_id);

CREATE TABLE work_vocal_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repertoire_item_id BIGINT NOT NULL,
    singer_id BIGINT NOT NULL,
    vocal_plan_id BIGINT NOT NULL,
    vocal_plan_division_id BIGINT NOT NULL,
    choir_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_work_vocal_assignment
        UNIQUE (repertoire_item_id, singer_id),

    CONSTRAINT fk_work_assignment_work
        FOREIGN KEY (repertoire_item_id, choir_id)
        REFERENCES repertoire_items (id, choir_id),

    CONSTRAINT fk_work_assignment_singer
        FOREIGN KEY (singer_id, choir_id)
        REFERENCES singers (id, choir_id),

    CONSTRAINT fk_work_assignment_plan
        FOREIGN KEY (vocal_plan_id, repertoire_item_id, choir_id)
        REFERENCES vocal_plans (id, repertoire_item_id, choir_id),

    CONSTRAINT fk_work_assignment_division
        FOREIGN KEY (vocal_plan_division_id, vocal_plan_id)
        REFERENCES vocal_plan_divisions (id, vocal_plan_id)
);

CREATE INDEX idx_work_vocal_assignments_work
    ON work_vocal_assignments (repertoire_item_id, choir_id);

CREATE INDEX idx_work_vocal_assignments_division
    ON work_vocal_assignments (vocal_plan_division_id, vocal_plan_id);
