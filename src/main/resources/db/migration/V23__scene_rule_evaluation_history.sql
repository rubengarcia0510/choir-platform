CREATE TABLE transition_rule_evaluations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transition_version_id BIGINT NOT NULL
        REFERENCES transition_versions(id),
    transition_id BIGINT NOT NULL
        REFERENCES transitions(id),
    from_formation_version_id BIGINT NOT NULL
        REFERENCES formation_versions(id),
    to_formation_version_id BIGINT NOT NULL
        REFERENCES formation_versions(id),
    repertoire_item_id BIGINT NOT NULL
        REFERENCES repertoire_items(id),
    separation_settings_revision BIGINT NOT NULL
        REFERENCES scene_rule_separation_setting_revisions(revision),
    global_separation_threshold DECIMAL(10, 7) NOT NULL,
    status VARCHAR(20) NOT NULL,
    evaluated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_transition_rule_evaluation_snapshots
        CHECK (from_formation_version_id <> to_formation_version_id),
    CONSTRAINT ck_transition_rule_evaluation_status
        CHECK (status IN ('SATISFIED', 'VIOLATED', 'NOT_EVALUABLE')),
    CONSTRAINT ck_transition_rule_evaluation_threshold
        CHECK (
            global_separation_threshold > 0
            AND global_separation_threshold * global_separation_threshold <= 2
        )
);

CREATE INDEX idx_transition_rule_evaluations_version
    ON transition_rule_evaluations (transition_version_id, id DESC);

CREATE TABLE transition_rule_evaluation_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluation_id BIGINT NOT NULL
        REFERENCES transition_rule_evaluations(id),
    result_order INTEGER NOT NULL,
    scene_rule_id BIGINT NOT NULL REFERENCES scene_rules(id),
    rule_revision_id BIGINT NOT NULL REFERENCES scene_rule_revisions(id),
    rule_type VARCHAR(30) NOT NULL,
    status VARCHAR(20) NOT NULL,
    code VARCHAR(100) NOT NULL,
    explanation VARCHAR(1000) NOT NULL,
    CONSTRAINT uq_transition_rule_evaluation_result
        UNIQUE (evaluation_id, result_order),
    CONSTRAINT ck_transition_rule_result_order CHECK (result_order >= 0),
    CONSTRAINT ck_transition_rule_result_status
        CHECK (status IN ('SATISFIED', 'VIOLATED', 'NOT_EVALUABLE'))
);

CREATE TABLE transition_rule_evaluation_warnings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluation_id BIGINT NOT NULL
        REFERENCES transition_rule_evaluations(id),
    result_order INTEGER,
    warning_order INTEGER NOT NULL,
    code VARCHAR(100) NOT NULL,
    explanation VARCHAR(1000) NOT NULL,
    status VARCHAR(20) NOT NULL,
    CONSTRAINT fk_transition_rule_warning_result
        FOREIGN KEY (evaluation_id, result_order)
        REFERENCES transition_rule_evaluation_results(evaluation_id, result_order),
    CONSTRAINT ck_transition_rule_warning_order CHECK (warning_order >= 0),
    CONSTRAINT ck_transition_rule_warning_status
        CHECK (status IN ('SATISFIED', 'VIOLATED', 'NOT_EVALUABLE'))
);
