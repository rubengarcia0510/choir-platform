CREATE TABLE scene_rule_separation_setting_revisions (
    revision BIGINT PRIMARY KEY,
    previous_threshold DECIMAL(10, 7),
    new_threshold DECIMAL(10, 7) NOT NULL,
    changed_by_email VARCHAR(320) NOT NULL,
    changed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_scene_rule_separation_revision
        CHECK (revision > 0),
    CONSTRAINT ck_scene_rule_separation_threshold
        CHECK (
            new_threshold > 0
            AND new_threshold * new_threshold <= 2
            AND (
                previous_threshold IS NULL
                OR previous_threshold > 0
                    AND previous_threshold * previous_threshold <= 2
            )
        )
);

CREATE TABLE scene_rule_separation_settings (
    id SMALLINT PRIMARY KEY,
    revision BIGINT NOT NULL
        REFERENCES scene_rule_separation_setting_revisions(revision),
    threshold DECIMAL(10, 7) NOT NULL,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by_email VARCHAR(320) NOT NULL,
    CONSTRAINT ck_scene_rule_separation_settings_id CHECK (id = 1),
    CONSTRAINT ck_scene_rule_separation_settings_threshold
        CHECK (threshold > 0 AND threshold * threshold <= 2)
);

