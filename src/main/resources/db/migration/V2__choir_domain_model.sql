CREATE TABLE directors (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
display_name VARCHAR(160) NOT NULL,
email VARCHAR(254) NOT NULL UNIQUE,
created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE choirs (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
director_id BIGINT NOT NULL REFERENCES directors(id),
name VARCHAR(160) NOT NULL,
description VARCHAR(1000),
created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
CONSTRAINT uq_choir_director_name UNIQUE (director_id, name),
CONSTRAINT uq_choir_id_director UNIQUE (id, director_id)
);

CREATE TABLE singers (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
choir_id BIGINT NOT NULL REFERENCES choirs(id),
display_name VARCHAR(160) NOT NULL,
email VARCHAR(254),
voice_part VARCHAR(40),
active BOOLEAN NOT NULL DEFAULT TRUE,
created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
CONSTRAINT uq_singer_id_choir UNIQUE (id, choir_id)
);

CREATE TABLE concerts (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
choir_id BIGINT NOT NULL REFERENCES choirs(id),
title VARCHAR(200) NOT NULL,
concert_date DATE,
venue VARCHAR(250),
status VARCHAR(20) NOT NULL DEFAULT 'PLANNED',
published_at TIMESTAMP,
created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
CONSTRAINT ck_concert_status
CHECK (status IN ('PLANNED', 'PUBLISHED', 'COMPLETED', 'CANCELLED'))
);

CREATE TABLE concert_cast_snapshots (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
concert_id BIGINT NOT NULL REFERENCES concerts(id),
source_singer_id BIGINT REFERENCES singers(id) ON DELETE SET NULL,
singer_name_snapshot VARCHAR(160) NOT NULL,
voice_part_snapshot VARCHAR(40),
captured_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_cast_snapshot_concert
ON concert_cast_snapshots(concert_id);

CREATE TABLE repertoire_items (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
choir_id BIGINT NOT NULL REFERENCES choirs(id),
title VARCHAR(200) NOT NULL,
composer VARCHAR(160),
arranger VARCHAR(160),
notes VARCHAR(2000),
created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
CONSTRAINT uq_repertoire_id_choir UNIQUE (id, choir_id)
);

CREATE TABLE concert_repertoire (
concert_id BIGINT NOT NULL REFERENCES concerts(id),
repertoire_item_id BIGINT NOT NULL REFERENCES repertoire_items(id),
order_index INTEGER NOT NULL,
PRIMARY KEY (concert_id, repertoire_item_id),
CONSTRAINT ck_repertoire_order CHECK (order_index >= 0)
);

CREATE TABLE formations (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
choir_id BIGINT NOT NULL REFERENCES choirs(id),
name VARCHAR(160) NOT NULL,
description VARCHAR(1000),
created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
CONSTRAINT uq_formation_id_choir UNIQUE (id, choir_id)
);

CREATE TABLE formation_versions (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
formation_id BIGINT NOT NULL REFERENCES formations(id),
version_number INTEGER NOT NULL,
status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
notes VARCHAR(2000),
created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
published_at TIMESTAMP,
CONSTRAINT uq_formation_version UNIQUE (formation_id, version_number),
CONSTRAINT ck_formation_version_number CHECK (version_number > 0),
CONSTRAINT ck_formation_version_status
CHECK (status IN ('DRAFT', 'PUBLISHED', 'ARCHIVED'))
);

CREATE TABLE formation_positions (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
formation_version_id BIGINT NOT NULL
REFERENCES formation_versions(id),
singer_id BIGINT REFERENCES singers(id) ON DELETE SET NULL,
singer_name_snapshot VARCHAR(160) NOT NULL,
voice_part_snapshot VARCHAR(40),
position_label VARCHAR(80),
x_coordinate DECIMAL(10, 3) NOT NULL,
y_coordinate DECIMAL(10, 3) NOT NULL,
created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_formation_positions_version
ON formation_positions(formation_version_id);

CREATE TABLE transitions (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
choir_id BIGINT NOT NULL REFERENCES choirs(id),
name VARCHAR(160) NOT NULL,
description VARCHAR(1000),
created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
CONSTRAINT uq_transition_id_choir UNIQUE (id, choir_id)
);

CREATE TABLE transition_versions (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
transition_id BIGINT NOT NULL REFERENCES transitions(id),
version_number INTEGER NOT NULL,
from_formation_version_id BIGINT NOT NULL
REFERENCES formation_versions(id),
to_formation_version_id BIGINT NOT NULL
REFERENCES formation_versions(id),
status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
instructions VARCHAR(4000),
created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
published_at TIMESTAMP,
CONSTRAINT uq_transition_version UNIQUE (transition_id, version_number),
CONSTRAINT ck_transition_version_number CHECK (version_number > 0),
CONSTRAINT ck_transition_version_status
CHECK (status IN ('DRAFT', 'PUBLISHED', 'ARCHIVED')),
CONSTRAINT ck_transition_different_formations
CHECK (from_formation_version_id <> to_formation_version_id)
);

CREATE TABLE absences (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
singer_id BIGINT NOT NULL REFERENCES singers(id),
concert_id BIGINT REFERENCES concerts(id),
start_date DATE NOT NULL,
end_date DATE NOT NULL,
reason VARCHAR(500),
status VARCHAR(20) NOT NULL DEFAULT 'CONFIRMED',
created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
CONSTRAINT ck_absence_dates CHECK (end_date >= start_date),
CONSTRAINT ck_absence_status
CHECK (status IN ('REPORTED', 'CONFIRMED', 'CANCELLED'))
);

CREATE INDEX idx_choirs_director ON choirs(director_id);
CREATE INDEX idx_singers_choir ON singers(choir_id);
CREATE INDEX idx_concerts_choir_date ON concerts(choir_id, concert_date);
CREATE INDEX idx_repertoire_choir ON repertoire_items(choir_id);
CREATE INDEX idx_formations_choir ON formations(choir_id);
CREATE INDEX idx_transitions_choir ON transitions(choir_id);
CREATE INDEX idx_absences_singer_dates ON absences(singer_id, start_date, end_date);
