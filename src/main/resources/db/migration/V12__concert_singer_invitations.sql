-- CHOIR-14: invitaciones individuales de coreutas a un concierto.
-- Se almacena el hash del token, nunca el token original.
-- La revocación es individual y se valida en cada acceso.

CREATE TABLE concert_singer_invitations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    choir_id BIGINT NOT NULL,
    concert_id BIGINT NOT NULL,
    singer_id BIGINT NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMP,
    revoked_at TIMESTAMP,

    CONSTRAINT fk_invitation_concert_same_choir
        FOREIGN KEY (concert_id, choir_id)
        REFERENCES concerts (id, choir_id),

    CONSTRAINT fk_invitation_singer_same_choir
        FOREIGN KEY (singer_id, choir_id)
        REFERENCES singers (id, choir_id),

    CONSTRAINT uq_concert_singer_invitation_token
        UNIQUE (token_hash),

    CONSTRAINT ck_invitation_expiry
        CHECK (expires_at IS NULL OR expires_at > created_at)
);

CREATE INDEX idx_concert_singer_invitations_lookup
    ON concert_singer_invitations (concert_id, singer_id);

CREATE INDEX idx_concert_singer_invitations_active
    ON concert_singer_invitations (token_hash, revoked_at, expires_at);
